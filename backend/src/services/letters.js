// PDF output: confirmation letter (spec §7 "Download Confirmation Letter") and placeholder documents.
import PDFDocument from 'pdfkit';
import { fmtDate, fmtRange, fmtDateTime } from '../domain/dates.js';
import { config } from '../config.js';
import { planText } from '../domain/sessionPlan.js';

const GREEN = '#0f4a30';
const GREY = '#55625a';

function pdfBuffer(build) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 56, info: { Producer: 'Holiday Dialysis Coordination Portal' } });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    build(doc);
    doc.end();
  });
}

export function samplePdf(title, text) {
  return pdfBuffer((doc) => {
    doc.fillColor(GREEN).fontSize(18).text(title);
    doc.moveDown().fillColor('#000').fontSize(11).text(text);
  });
}

/** @param {object} r request detail (requests service shape) @param {object} decision approved decision */
export function confirmationLetterPdf(r, decision) {
  const facility = r.selectedFacilityName || r.receivingFacilityName || r.freeTextFacility || '—';
  const rows = [
    ['Patient', r.patientName],
    ['MRN', r.mrn],
    ['Home clinic', r.requestingFacilityName],
    ['Receiving facility', facility],
    ['Destination', [r.destinationCity, r.destinationCountryName].filter(Boolean).join(', ')],
    ['Travel dates', fmtRange(r.travelStart, r.travelEnd)],
    ['Confirmed sessions', fmtRange(decision.confirmedStart, decision.confirmedEnd)],
    ['Sessions requested', String(r.sessionsRequired ?? '—')],
    ...(r.sessionPlan?.length ? [['Requested days & shifts', planText(r.sessionPlan)]] : []),
    ['Modality', r.modality || 'Haemodialysis'],
  ];
  if (decision.notes) rows.push(['Facility notes', decision.notes]);

  return pdfBuffer((doc) => {
    const left = doc.page.margins.left;
    const width = doc.page.width - left - doc.page.margins.right;
    doc.fillColor(GREEN).font('Helvetica-Bold').fontSize(14).text('Holiday Dialysis Coordination', left, 56);
    doc.fillColor(GREY).font('Helvetica').fontSize(10).text(r.requestingFacilityName || '', left, 76);
    doc.text(`Ref. ${r.requestNumber}`, left, 56, { width, align: 'right' });
    doc.text(fmtDate(new Date().toISOString().slice(0, 10)), left, 70, { width, align: 'right' });
    doc.moveTo(left, 98).lineTo(left + width, 98).lineWidth(1.5).strokeColor(GREEN).stroke();

    doc.moveDown(2).fillColor(GREEN).font('Helvetica-Bold').fontSize(16).text('Confirmation of Holiday Dialysis Sessions', left, 120);
    doc.moveDown(0.6).fillColor('#1b241f').font('Helvetica').fontSize(11)
      .text('This letter confirms that holiday dialysis sessions have been arranged for the patient below.', { width });
    doc.moveDown(1);
    for (const [k, v] of rows) {
      const y = doc.y;
      doc.fillColor(GREY).font('Helvetica').fontSize(10.5).text(k, left, y, { width: 170 });
      doc.fillColor('#1b241f').font(k === 'Confirmed sessions' || k === 'Patient' ? 'Helvetica-Bold' : 'Helvetica')
        .text(String(v ?? '—'), left + 180, y, { width: width - 180 });
      doc.moveDown(0.5);
    }
    doc.moveDown(1).font('Helvetica').fontSize(11).fillColor('#1b241f')
      .text('Please bring this letter, a photo ID and a current medication list to the first session.', left, doc.y, { width });
    doc.moveDown(1.5).fillColor(GREY).fontSize(9.5)
      .text(`Confirmed by ${decision.decidedByName} on ${fmtDateTime(decision.decidedAt, config.timeZone)}. Generated by the Holiday Dialysis Coordination Portal.`, { width });
  });
}
